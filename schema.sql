-- FTG SUPABASE DATABASE
create table if not exists public.events (
 id bigint generated by default as identity primary key,
 title text not null,
 event_date timestamptz not null,
 venue text,
 description text,
 ticket_url text,
 poster_url text,
 status text default 'UPCOMING',
 published boolean default false,
 created_at timestamptz default now()
);
create table if not exists public.fighters (
 id bigint generated by default as identity primary key,
 name text not null,
 role text,
 record text,
 image_url text,
 card_order int default 0,
 published boolean default false,
 created_at timestamptz default now()
);
create table if not exists public.media (
 id bigint generated by default as identity primary key,
 title text not null,
 type text,
 video_url text,
 thumbnail_url text,
 published boolean default false,
 created_at timestamptz default now()
);
create table if not exists public.live_settings (
 id int primary key,
 event_id bigint references public.events(id),
 online boolean default false,
 youtube_id text,
 title text default 'FTG LIVE',
 updated_at timestamptz default now()
);
create table if not exists public.orders (
 id bigint generated by default as identity primary key,
 event_id bigint references public.events(id),
 customer_email text,
 amount_cents int,
 status text default 'paid',
 stripe_session_id text,
 created_at timestamptz default now()
);
create table if not exists public.site_stats (
 id bigint generated by default as identity primary key,
 metric text,
 value bigint default 0,
 recorded_at timestamptz default now()
);

alter table public.events enable row level security;
alter table public.fighters enable row level security;
alter table public.media enable row level security;
alter table public.live_settings enable row level security;
alter table public.orders enable row level security;
alter table public.site_stats enable row level security;

create policy "public published events" on public.events for select using (published=true);
create policy "public published fighters" on public.fighters for select using (published=true);
create policy "public published media" on public.media for select using (published=true);
create policy "public live settings" on public.live_settings for select using (true);
